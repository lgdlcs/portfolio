"""Digitize img/avatar.png into js/avatar.js (ASCII rows used by the terminal and the hologram).

Usage: python tools/ascii-avatar.py [--cols N] [--preview out.png]
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter, ImageFont, ImageOps

ROOT = Path(__file__).resolve().parent.parent
RAMP = " .:-=+*#%@"
CROP = (50, 30, 410, 390)  # head and shoulders, so the face gets more cells


def silhouette(x, y):
    """Soft head + shoulders mask in 460x460 photo space, 0..1."""
    head = ((x - 230) / 84) ** 2 + ((y - 165) / 120) ** 2
    torso = ((x - 230) / 235) ** 2 + ((y - 510) / 225) ** 2
    return max(0.0, min(1.0, (1.15 - min(head, torso)) / 0.15))


def digitize(cols):
    rows = cols // 2  # terminal cells are ~2x taller than wide
    photo = Image.open(ROOT / "img/avatar.png").convert("RGB")
    img = photo.convert("L")
    hsv = photo.convert("HSV").get_flattened_data()
    mask = Image.new("L", img.size)
    # Drop the bright, grey office background that the ellipses still overlap (skin is saturated).
    mask.putdata([
        0 if (v > 150 and sat < 45) else int(255 * silhouette(i % img.width, i // img.width))
        for i, (_, sat, v) in enumerate(hsv)
    ])
    mask = mask.filter(ImageFilter.MedianFilter(7))
    # Equalize against the person only, so the bright office background does not flatten the face.
    img, mask = img.crop(CROP), mask.crop(CROP)
    img = ImageOps.equalize(img, mask=mask).filter(ImageFilter.UnsharpMask(radius=3, percent=180))
    small = img.resize((cols, rows), Image.LANCZOS)
    small_mask = mask.resize((cols, rows), Image.BILINEAR)

    lines = []
    for r in range(rows):
        row = ""
        for c in range(cols):
            m = small_mask.getpixel((c, r)) / 255
            if m < 0.35:
                row += " "
                continue
            level = (small.getpixel((c, r)) / 255) ** 1.1
            row += RAMP[max(1, min(len(RAMP) - 1, round(level * (len(RAMP) - 1))))]
        lines.append(row.rstrip())
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return lines


def preview(lines, out):
    font = ImageFont.truetype("C:/Windows/Fonts/consola.ttf", 14)
    w = max(map(len, lines)) * 8 + 16
    im = Image.new("RGB", (w, len(lines) * 16 + 16), (10, 10, 10))
    d = ImageDraw.Draw(im)
    for i, line in enumerate(lines):
        d.text((8, 8 + i * 16), line, font=font, fill=(34, 211, 238))
    im.save(out)


ap = argparse.ArgumentParser()
ap.add_argument("--cols", type=int, default=76)
ap.add_argument("--preview")
args = ap.parse_args()

lines = digitize(args.cols)
if args.preview:
    preview(lines, args.preview)
else:
    body = ",\n".join("    '" + l.replace("\\", "\\\\").replace("'", "\\'") + "'" for l in lines)
    (ROOT / "js/avatar.js").write_text(
        "// Generated by tools/ascii-avatar.py from img/avatar.png — do not edit by hand.\n"
        f"const AVATAR_RAMP = '{RAMP}';\nconst AVATAR_ASCII = [\n{body},\n];\n",
        encoding="utf-8",
    )
    print("\n".join(lines))
